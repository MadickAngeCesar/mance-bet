function buildMarketGroup(params: {
  marketKey: string;
  marketName: string;
  modelVersion: string;
  algorithmName: string;
  modelReliability: number;
  bookmakerName: string;
  capturedAt: string;
  dataFreshnessMinutes: number;
  isVerifiedOdds: boolean;
  outcomesInput: {
    selectionKey: string;
    selectionLabel: string;
    line?: number;
    decimalOdds: number;
    modelProbability: number;
  }[];
}): MarketPredictionGroup {
  const {
    marketKey,
    marketName,
    modelVersion,
    algorithmName,
    modelReliability,
    bookmakerName,
    capturedAt,
    dataFreshnessMinutes,
    isVerifiedOdds,
    outcomesInput,
  } = params;

  const oddsList = outcomesInput.map((o) => o.decimalOdds);
  const { rawProbabilities, fairProbabilities, overroundPct } =
    removeBookmakerMargin(oddsList);

  const outcomes = outcomesInput.map((item, idx) => {
    const valCheck = evaluateValueQualification({
      modelProbability: item.modelProbability,
      decimalOdds: item.decimalOdds,
      modelReliability,
      dataFreshnessMinutes,
      isVerifiedOdds,
      minEvThreshold: 0.025,
      minModelProbability: 0.18,
      minReliabilityThreshold: 0.74,
    });

    return {
      selectionKey: item.selectionKey,
      selectionLabel: item.selectionLabel,
      line: item.line,
      bookmakerName,
      decimalOdds: item.decimalOdds,
      rawImpliedProbability: rawProbabilities[idx],
      fairMarketProbability: fairProbabilities[idx],
      overroundPct,
      modelProbability: item.modelProbability,
      expectedValue: valCheck.expectedValue,
      isValueFlagged: valCheck.isFlaggedValue,
      valueDisqualificationReason: valCheck.disqualificationReasons[0],
      capturedAt,
    };
  });

  const bestModelOutcome = [...outcomes].sort(
    (a, b) => b.modelProbability - a.modelProbability
  )[0];

  const confidenceTier =
    modelReliability >= 0.82 && bestModelOutcome.modelProbability >= 0.56
      ? 'high_calibrated'
      : modelReliability >= 0.74
      ? 'moderate_calibrated'
      : 'low_sample_caution';

  return {
    marketKey,
    marketName,
    modelVersion,
    algorithmName,
    modelReliability,
    confidenceTier,
    outcomes,
    recommendedSelectionKey: bestModelOutcome?.selectionKey,
  };
}

